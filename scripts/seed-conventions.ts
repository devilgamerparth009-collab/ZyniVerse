async function main() {
  console.log("Seeding verified conventions...");

  for (const conv of CONVENTIONS) {
    await prisma.convention.upsert({
      where: { id: conv.id },
      update: conv,
      create: conv,
    });
  }

  await prisma.convention.updateMany({
    where: { id: { in: LEGACY_UNVERIFIED_IDS } },
    data: { isPublic: false },
  });

  const count = await prisma.convention.count({ where: { isPublic: true } });
  console.log(`Done! ${count} verified conventions are public.`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
