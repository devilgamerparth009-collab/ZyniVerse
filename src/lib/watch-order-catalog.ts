// Server-side loader for the full anime watch-order catalog.
//
// The raw source is ~3 MB, so it is fetched and normalized on the server and
// only compact entries are sent to the browser. The external response is
// cached by Next's data cache (6h revalidate) and this module keeps a short
// in-process copy so concurrent requests don't re-normalize the same payload.
//
// One extra cached AniList list query adds relation-based entries for popular
// anime that aren't in the curated r/anime dataset. No per-card AniList calls.

import { getPopular, getTopRated } from "@/lib/anilist";

const SOURCE_URL =
  "https://raw.githubusercontent.com/Bas1874/Anime-Watch-Order-Api/main/data/watch_order_api.json";
const REPO_URL = "https://github.com/Bas1874/Anime-Watch-Order-Api";
const ANILIST_URL = "https://anilist.co";
// AniList caps `Page.perPage` at 50, so two cached lists = 100 candidates
// without any per-card GraphQL calls.
const ANILIST_EXTRA_LIMIT = 50;
const REVALIDATE_SECONDS = 6 * 60 * 60;

export interface WatchOrderCatalogSource {
  name: string;
  apiUrl: string;
  repoUrl: string;
  anilistUrl: string;
  wikiUrl: string | null;
  version: string | null;
  lastUpdated: string | null;
  stale: boolean;
}

export type WatchOrderCatalogSourceType = "verified" | "auto";

export interface WatchOrderCatalogItem {
  id: number;
  sourceType: WatchOrderCatalogSourceType;
  title: string;
  romaji?: string;
  native?: string;
  franchise: string;
  orderName: string;
  stepTitle: string;
  step: number;
  isOptional: boolean;
  format?: string;
  episodes?: number;
  score?: number;
  popularity?: number;
  year?: number;
  genres: string[];
  cover?: string;
  color?: string;
  orderNames: string[];
  referenceCount: number;
}

export interface WatchOrderCatalog {
  source: WatchOrderCatalogSource;
  counts: {
    series: number;
    orders: number;
    steps: number;
    uniqueAnime: number;
    curatedAnime: number;
    autoGenerated: number;
  };
  items: WatchOrderCatalogItem[];
}

interface RawMediaTitle {
  romaji?: string | null;
  english?: string | null;
  native?: string | null;
  userPreferred?: string | null;
}

interface RawMedia {
  id?: number | null;
  title?: RawMediaTitle | null;
  format?: string | null;
  episodes?: number | null;
  averageScore?: number | null;
  popularity?: number | null;
  seasonYear?: number | null;
  genres?: string[] | null;
  coverImage?: {
    extraLarge?: string | null;
    large?: string | null;
    medium?: string | null;
    color?: string | null;
  } | null;
}

interface RawStep {
  step_title?: string | null;
  is_optional?: boolean | null;
  media?: RawMedia | null;
}

interface RawOrder {
  name?: string | null;
  description?: string | null;
  steps?: RawStep[] | null;
}

interface RawSeries {
  title?: string | null;
  alternative_titles?: string[] | null;
  watch_orders?: RawOrder[] | null;
}

interface RawSource {
  metadata?: {
    version?: string | null;
    last_updated_utc?: string | null;
    source_url?: string | null;
  } | null;
  data?: RawSeries[] | null;
}

function cleanString(value: unknown): string | undefined {
  return typeof value === "string" && value.trim() ? value.trim() : undefined;
}

function pickTitle(media: RawMedia): string {
  return (
    cleanString(media.title?.userPreferred) ||
    cleanString(media.title?.english) ||
    cleanString(media.title?.romaji) ||
    cleanString(media.title?.native) ||
    "Untitled anime"
  );
}

let memoryCache: { value: WatchOrderCatalog; expiresAt: number } | null = null;
let inFlight: Promise<WatchOrderCatalog> | null = null;

async function loadCatalog(): Promise<WatchOrderCatalog> {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 15_000);

  let raw: RawSource;
  try {
    const response = await fetch(SOURCE_URL, {
      cache: "force-cache",
      next: { revalidate: REVALIDATE_SECONDS },
      signal: controller.signal,
      headers: { Accept: "application/json" },
    });
    if (!response.ok) {
      throw new Error(`Watch-order source responded ${response.status}`);
    }
    raw = (await response.json()) as RawSource;
  } finally {
    clearTimeout(timer);
  }

  const seriesList = Array.isArray(raw.data) ? raw.data : [];
  const byId = new Map<number, WatchOrderCatalogItem>();
  let orderCount = 0;
  let stepCount = 0;

  for (const series of seriesList) {
    const franchise = cleanString(series.title) || "Anime franchise";
    const orders = Array.isArray(series.watch_orders) ? series.watch_orders : [];

    for (const order of orders) {
      orderCount += 1;
      const orderName = cleanString(order.name) || "Watch order";
      const steps = Array.isArray(order.steps) ? order.steps : [];

      steps.forEach((step, index) => {
        stepCount += 1;
        const media = step.media;
        const id = Number(media?.id);
        if (!media || !Number.isFinite(id) || id <= 0) return;

        const title = pickTitle(media);
        const stepTitle = cleanString(step.step_title) || title;
        const existing = byId.get(id);

        if (existing) {
          existing.referenceCount += 1;
          if (existing.orderNames.length < 6 && !existing.orderNames.includes(orderName)) {
            existing.orderNames.push(orderName);
          }
          return;
        }

        const cover = media.coverImage;
        const genres = Array.isArray(media.genres)
          ? media.genres.filter((genre): genre is string => typeof genre === "string")
          : [];

        byId.set(id, {
          id,
          sourceType: "verified",
          title,
          romaji: cleanString(media.title?.romaji) || undefined,
          native: cleanString(media.title?.native) || undefined,
          franchise,
          orderName,
          stepTitle,
          step: index + 1,
          isOptional: Boolean(step.is_optional),
          format: cleanString(media.format) || undefined,
          episodes:
            typeof media.episodes === "number" && media.episodes > 0
              ? media.episodes
              : undefined,
          score:
            typeof media.averageScore === "number" && media.averageScore > 0
              ? media.averageScore
              : undefined,
          popularity:
            typeof media.popularity === "number" && media.popularity > 0
              ? media.popularity
              : undefined,
          year:
            typeof media.seasonYear === "number" && media.seasonYear > 0
              ? media.seasonYear
              : undefined,
          genres,
          cover:
            cleanString(cover?.large) ||
            cleanString(cover?.medium) ||
            cleanString(cover?.extraLarge) ||
            undefined,
          color: cleanString(cover?.color) || undefined,
          orderNames: [orderName],
          referenceCount: 1,
        });
      });
    }
  }

  const curatedCount = byId.size;
  let autoCount = 0;

  // Two cached AniList list queries cover popular/top-rated anime missing from
  // the curated dataset. Their watch order is generated on the detail page from
  // AniList relations, so this route never needs per-card GraphQL calls.
  try {
    const [popular, topRated] = await Promise.all([
      getPopular(ANILIST_EXTRA_LIMIT),
      getTopRated(ANILIST_EXTRA_LIMIT),
    ]);
    for (const media of [...popular, ...topRated]) {
      const id = Number(media?.id);
      if (!Number.isFinite(id) || id <= 0 || byId.has(id)) continue;

      const title = pickTitle(media);
      const cover = media.coverImage;
      const orderName = "Relation-based watch order";
      byId.set(id, {
        id,
        sourceType: "auto",
        title,
        romaji: cleanString(media.title?.romaji) || undefined,
        native: cleanString(media.title?.native) || undefined,
        franchise: "AniList relations · auto-generated",
        orderName,
        stepTitle: title,
        step: 1,
        isOptional: false,
        format: cleanString(media.format) || undefined,
        episodes:
          typeof media.episodes === "number" && media.episodes > 0
            ? media.episodes
            : undefined,
        score:
          typeof media.averageScore === "number" && media.averageScore > 0
            ? media.averageScore
            : undefined,
        popularity:
          typeof media.popularity === "number" && media.popularity > 0
            ? media.popularity
            : undefined,
        year:
          typeof media.startDate?.year === "number" && media.startDate.year > 0
            ? media.startDate.year
            : undefined,
        genres: Array.isArray(media.genres)
          ? media.genres.filter((genre): genre is string => typeof genre === "string")
          : [],
        cover:
          cleanString(cover?.large) ||
          cleanString(cover?.medium) ||
          cleanString(cover?.extraLarge) ||
          undefined,
        color: cleanString(cover?.color) || undefined,
        orderNames: [orderName],
        referenceCount: 1,
      });
      autoCount += 1;
    }
  } catch {
    // AniList outage must not take down the curated catalog.
  }

  const items = [...byId.values()].sort(
    (a, b) =>
      (b.popularity ?? 0) - (a.popularity ?? 0) ||
      (b.score ?? 0) - (a.score ?? 0) ||
      a.title.localeCompare(b.title),
  );

  return {
    source: {
      name: "Anime Watch Order API",
      apiUrl: SOURCE_URL,
      repoUrl: REPO_URL,
      anilistUrl: ANILIST_URL,
      wikiUrl: cleanString(raw.metadata?.source_url) || null,
      version: cleanString(raw.metadata?.version) || null,
      lastUpdated: cleanString(raw.metadata?.last_updated_utc) || null,
      stale: false,
    },
    counts: {
      series: seriesList.length,
      orders: orderCount,
      steps: stepCount,
      uniqueAnime: items.length,
      curatedAnime: curatedCount,
      autoGenerated: autoCount,
    },
    items,
  };
}

export async function getWatchOrderCatalog(): Promise<WatchOrderCatalog> {
  const now = Date.now();
  if (memoryCache && memoryCache.expiresAt > now) return memoryCache.value;
  if (inFlight) return inFlight;

  inFlight = loadCatalog()
    .then((value) => {
      memoryCache = {
        value,
        expiresAt: Date.now() + REVALIDATE_SECONDS * 1000,
      };
      return value;
    })
    .catch((error: unknown) => {
      if (memoryCache) {
        return {
          ...memoryCache.value,
          source: { ...memoryCache.value.source, stale: true },
        };
      }
      throw error;
    })
    .finally(() => {
      inFlight = null;
    });

  return inFlight;
}
