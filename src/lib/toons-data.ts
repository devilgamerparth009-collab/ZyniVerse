/** Formats only the years we can verify; callers omit the label when empty. */
export function formatToonYears(toon: CartoonEntry) {
  if (toon.releaseYear == null) return "";
  return `${toon.releaseYear}${toon.endYear ? ` – ${toon.endYear}` : ""}`;
}

